/// Shared renderer for the profile-change OTP pages.
fn render_confirm(
    user: &CurrentUser,
    title: &str,
    summary: Vec<(String, String)>,
    action_url: &str,
    challenge: crate::services::action_otp_service::ActionChallenge,
) -> Result<HttpResponse, AppError> {
    let body = OtpConfirmPage {
        layout: LayoutCtx::from_user(Some(user)),
        title: title.to_string(),
        summary,
        action_url: action_url.to_string(),
        cancel_url: "/settings/telegram".to_string(),
        action_id: challenge.action_id,
        demo_otp: if challenge.delivered { None } else { Some(challenge.otp) },
        error: None,
    }
    .render()
    .map_err(|e| AppError::Internal(anyhow::anyhow!("settings template: {e}")))?;
    Ok(HttpResponse::Ok()
        .content_type("text/html; charset=utf-8")
        .body(body))
}

/// Inline retry: wrong code, action still pending - same page, same action id.
fn render_otp_retry(
    user: &CurrentUser,
    title: &str,
    action_url: &str,
    action_id: i64,
    error: String,
) -> Result<HttpResponse, AppError> {
    let body = OtpConfirmPage {
        layout: LayoutCtx::from_user(Some(user)),
        title: title.to_string(),
        summary: vec![],
        action_url: action_url.to_string(),
        cancel_url: "/settings/telegram".to_string(),
        action_id,
        demo_otp: None,
        error: Some(error),
    }
    .render()
    .map_err(|e| AppError::Internal(anyhow::anyhow!("settings template: {e}")))?;
    Ok(HttpResponse::Ok()
        .content_type("text/html; charset=utf-8")
        .body(body))
}

/// Cancel a bot-scheduled unlink. Requires the website session (password
/// authenticated), which is exactly the channel an attacker inside a stolen
/// Telegram account does NOT have.
async fn telegram_unlink_cancel(
    state: web::Data<AppState>,
    user: CurrentUser,
) -> Result<HttpResponse, AppError> {
    customers_only(&user)?;
    let cancelled = sqlx::query(
        r#"UPDATE users SET telegram_unlink_at = NULL WHERE id = $1 AND telegram_unlink_at IS NOT NULL"#,
    )
    .bind(user.id)
    .execute(&state.db)
    .await?;
    if cancelled.rows_affected() > 0 {
        crate::services::audit_service::notify(
            &state.db,
            user.id,
            "The scheduled Telegram unlink was cancelled. If you didn't request that unlink, change your password now.",
        )
        .await;
        let _ = sqlx::query(
            r#"INSERT INTO audit_log (actor_user_id, event, payload) VALUES ($1, 'telegram.unlink_cancelled', '{}'::jsonb)"#,
        )
        .bind(user.id)
        .execute(&state.db)
        .await;
    }
    Ok(HttpResponse::Found()
        .insert_header(("Location", "/settings/telegram"))
        .finish())
}
